-- Additive production migration. Supervisors are contacts, never login roles.
BEGIN;

CREATE TABLE public.academic_supervisors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint UNIQUE REFERENCES public.users(id) ON DELETE SET NULL,
    name varchar(150) NOT NULL CHECK (length(btrim(name)) > 1),
    staff_id varchar(50) NOT NULL CHECK (length(btrim(staff_id)) > 0),
    email varchar(150) NOT NULL CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    phone varchar(30),
    campus varchar(100) NOT NULL CHECK (length(btrim(campus)) > 0),
    faculty varchar(100) NOT NULL CHECK (length(btrim(faculty)) > 0),
    programme varchar(150) NOT NULL CHECK (length(btrim(programme)) > 0),
    email_approved_for_contact boolean NOT NULL DEFAULT false,
    created_by bigint NOT NULL REFERENCES public.admins(user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT academic_supervisor_scope_key UNIQUE (id,campus,faculty,programme)
);
CREATE UNIQUE INDEX uq_academic_supervisor_staff_scope ON public.academic_supervisors
    (lower(btrim(staff_id)),lower(btrim(campus)),lower(btrim(faculty)),lower(btrim(programme)));
CREATE UNIQUE INDEX uq_academic_supervisor_email_scope ON public.academic_supervisors
    (lower(btrim(email)),lower(btrim(campus)),lower(btrim(faculty)),lower(btrim(programme)));
CREATE INDEX idx_academic_supervisors_scope ON public.academic_supervisors (campus,faculty,programme,name);

ALTER TABLE public.students ADD COLUMN academic_supervisor_id bigint;
ALTER TABLE public.students ADD COLUMN academic_supervisor_assigned_at timestamptz;
ALTER TABLE public.students ADD CONSTRAINT students_academic_supervisor_scope_fk
    FOREIGN KEY (academic_supervisor_id,campus,faculty,programme)
    REFERENCES public.academic_supervisors (id,campus,faculty,programme) ON UPDATE RESTRICT ON DELETE RESTRICT;
ALTER TABLE public.students ADD CONSTRAINT students_academic_supervisor_date_check
    CHECK ((academic_supervisor_id IS NULL) = (academic_supervisor_assigned_at IS NULL));
CREATE INDEX idx_students_academic_supervisor ON public.students (academic_supervisor_id)
    WHERE academic_supervisor_id IS NOT NULL;

CREATE TABLE public.academic_supervisor_assignment_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(user_id),
    previous_supervisor_id bigint REFERENCES public.academic_supervisors(id),
    new_supervisor_id bigint REFERENCES public.academic_supervisors(id),
    changed_by bigint NOT NULL REFERENCES public.admins(user_id),
    internship_intake varchar(100),
    changed_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT academic_supervisor_history_change CHECK (previous_supervisor_id IS DISTINCT FROM new_supervisor_id)
);
CREATE INDEX idx_academic_supervisor_history_student ON public.academic_supervisor_assignment_history (student_id,changed_at DESC);
CREATE INDEX idx_academic_supervisor_history_actor ON public.academic_supervisor_assignment_history (changed_by,changed_at DESC);

ALTER TABLE public.academic_supervisors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.academic_supervisor_assignment_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.academic_supervisors, public.academic_supervisor_assignment_history FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.academic_supervisors_id_seq, public.academic_supervisor_assignment_history_id_seq FROM PUBLIC, anon, authenticated;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_app') THEN
        GRANT SELECT,INSERT,UPDATE ON public.academic_supervisors TO internpilih_app;
        GRANT SELECT,INSERT ON public.academic_supervisor_assignment_history TO internpilih_app;
        GRANT SELECT,UPDATE (academic_supervisor_id,academic_supervisor_assigned_at) ON public.students TO internpilih_app;
        GRANT USAGE ON SEQUENCE public.academic_supervisors_id_seq,public.academic_supervisor_assignment_history_id_seq TO internpilih_app;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_backend') THEN
        GRANT SELECT,INSERT,UPDATE ON public.academic_supervisors TO internpilih_backend;
        GRANT SELECT,INSERT ON public.academic_supervisor_assignment_history TO internpilih_backend;
        GRANT SELECT,UPDATE (academic_supervisor_id,academic_supervisor_assigned_at) ON public.students TO internpilih_backend;
        GRANT USAGE ON SEQUENCE public.academic_supervisors_id_seq,public.academic_supervisor_assignment_history_id_seq TO internpilih_backend;
    END IF;
END $$;
COMMIT;
