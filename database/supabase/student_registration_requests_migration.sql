-- Additive first-time student registration migration.
BEGIN;

ALTER TABLE public.users ADD COLUMN IF NOT EXISTS google_subject varchar(100);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_google_subject ON public.users (google_subject) WHERE google_subject IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.student_registration_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_auth_user_id varchar(100) NOT NULL,
    google_subject varchar(100) NOT NULL,
    google_profile_name varchar(150),
    google_picture_url text,
    email varchar(150) NOT NULL,
    matric_id varchar(10) NOT NULL CHECK (matric_id ~ '^[0-9]{10}$'),
    legal_name varchar(150) NOT NULL,
    phone varchar(30) NOT NULL,
    campus varchar(100) NOT NULL,
    faculty varchar(100) NOT NULL,
    programme varchar(150) NOT NULL,
    semester smallint NOT NULL CHECK (semester BETWEEN 1 AND 12),
    cgpa numeric(3,2) CHECK (cgpa BETWEEN 0 AND 4),
    coordinator_id bigint REFERENCES public.admins(user_id) ON DELETE SET NULL,
    document_bucket text NOT NULL DEFAULT 'documents' CHECK (document_bucket = 'documents'),
    document_path text NOT NULL,
    document_name varchar(150) NOT NULL,
    document_content_type varchar(30) NOT NULL CHECK (document_content_type IN ('application/pdf','image/jpeg','image/png')),
    document_bytes integer NOT NULL CHECK (document_bytes BETWEEN 1 AND 4194304),
    document_sha256 char(64) NOT NULL,
    status varchar(24) NOT NULL CHECK (status IN ('pending','pending_assignment','correction_required','approved','rejected')),
    review_reason text,
    submitted_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    reviewed_by bigint REFERENCES public.admins(user_id) ON DELETE SET NULL,
    approved_user_id bigint UNIQUE REFERENCES public.users(id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT registration_student_email CHECK (lower(email) = matric_id || '@student.uitm.edu.my'),
    CONSTRAINT registration_review_reason CHECK (status NOT IN ('rejected','correction_required') OR nullif(btrim(review_reason), '') IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_registration_google ON public.student_registration_requests (google_auth_user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_registration_google_subject ON public.student_registration_requests (google_subject);
CREATE UNIQUE INDEX IF NOT EXISTS uq_registration_email ON public.student_registration_requests (lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS uq_registration_active_matric ON public.student_registration_requests (matric_id)
    WHERE status IN ('pending','pending_assignment','correction_required','approved');
CREATE UNIQUE INDEX IF NOT EXISTS uq_registration_document ON public.student_registration_requests (document_bucket, document_path);
CREATE INDEX IF NOT EXISTS idx_registration_coordinator_status ON public.student_registration_requests (coordinator_id, status, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_registration_assignment ON public.student_registration_requests (campus, faculty, programme)
    WHERE status = 'pending_assignment';

ALTER TABLE public.student_registration_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.student_registration_requests FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.student_registration_requests_id_seq FROM PUBLIC, anon, authenticated;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_app') THEN
        GRANT INSERT ON public.users, public.students TO internpilih_app;
        GRANT USAGE ON SEQUENCE public.users_id_seq TO internpilih_app;
        GRANT SELECT, INSERT, UPDATE ON public.student_registration_requests TO internpilih_app;
        GRANT USAGE ON SEQUENCE public.student_registration_requests_id_seq TO internpilih_app;
        GRANT UPDATE (google_subject) ON public.users TO internpilih_app;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_backend') THEN
        GRANT INSERT ON public.users, public.students TO internpilih_backend;
        GRANT USAGE ON SEQUENCE public.users_id_seq TO internpilih_backend;
        GRANT SELECT, INSERT, UPDATE ON public.student_registration_requests TO internpilih_backend;
        GRANT USAGE ON SEQUENCE public.student_registration_requests_id_seq TO internpilih_backend;
        GRANT UPDATE (google_subject) ON public.users TO internpilih_backend;
    END IF;
END $$;

COMMIT;
