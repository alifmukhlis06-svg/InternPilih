BEGIN;

CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    phone varchar(30),
    password varchar(255) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'student' CHECK (role IN ('student','admin','employer')),
    created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.companies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    industry varchar(100) NOT NULL,
    location varchar(150) NOT NULL,
    allowance numeric(8,2),
    slots integer DEFAULT 3,
    work_mode varchar(20) DEFAULT 'On-site' CHECK (work_mode IN ('On-site','Hybrid','Remote')),
    hr_email varchar(150),
    status varchar(20) DEFAULT 'active' CHECK (status IN ('active','inactive')),
    created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.admins (
    user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    staff_id varchar(6) UNIQUE CHECK (staff_id IS NULL OR staff_id ~ '^[0-9]{6}$'),
    faculty varchar(100),
    programme varchar(150) UNIQUE
);

CREATE TABLE IF NOT EXISTS public.students (
    user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    matric_id varchar(20) UNIQUE,
    faculty varchar(100),
    programme varchar(150),
    coordinator_id bigint REFERENCES public.admins(user_id) ON DELETE SET NULL,
    cgpa numeric(3,2)
);
CREATE INDEX IF NOT EXISTS idx_students_coordinator ON public.students(coordinator_id);

CREATE TABLE IF NOT EXISTS public.employers (
    user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    company_id bigint REFERENCES public.companies(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_employers_company ON public.employers(company_id);

CREATE TABLE IF NOT EXISTS public.offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(user_id) ON DELETE CASCADE,
    company_id bigint NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    position varchar(150) NOT NULL,
    offer_date date NOT NULL,
    deadline date,
    status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','withdrawn')),
    response_date date,
    reject_reason text,
    application_id bigint,
    placement_verification_status varchar(20) NOT NULL DEFAULT 'not_submitted' CHECK (placement_verification_status IN ('not_submitted','pending','verified','rejected')),
    placement_verification_updated_at timestamptz,
    placement_verification_updated_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_offers_student ON public.offers(student_id);
CREATE INDEX IF NOT EXISTS idx_offers_company ON public.offers(company_id);
CREATE INDEX IF NOT EXISTS idx_offers_verification_user ON public.offers(placement_verification_updated_by);

CREATE TABLE IF NOT EXISTS public.documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(user_id) ON DELETE CASCADE,
    offer_id bigint REFERENCES public.offers(id) ON DELETE SET NULL,
    doc_type varchar(30) NOT NULL CHECK (doc_type IN ('offer_letter','agreement','student_id','supervisor_letter','other')),
    file_name varchar(255) NOT NULL,
    status varchar(20) DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    reject_reason varchar(255),
    reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    uploaded_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_documents_student ON public.documents(student_id);
CREATE INDEX IF NOT EXISTS idx_documents_offer ON public.documents(offer_id);
CREATE INDEX IF NOT EXISTS idx_documents_reviewed_by ON public.documents(reviewed_by);

CREATE TABLE IF NOT EXISTS public.internship_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(user_id) ON DELETE CASCADE,
    company_id bigint NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    position varchar(150) NOT NULL,
    source varchar(20) NOT NULL DEFAULT 'student' CHECK (source IN ('student','employer','coordinator')),
    status varchar(20) NOT NULL DEFAULT 'submitted' CHECK (status IN ('draft','submitted','shortlisted','interview','offered','rejected','withdrawn')),
    applied_at date NOT NULL,
    interview_at timestamptz,
    notes text,
    offer_id bigint REFERENCES public.offers(id) ON DELETE SET NULL,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_applications_student ON public.internship_applications(student_id);
CREATE INDEX IF NOT EXISTS idx_applications_company ON public.internship_applications(company_id);
CREATE INDEX IF NOT EXISTS idx_applications_offer ON public.internship_applications(offer_id);

-- offers.application_id and internship_applications.offer_id form a nullable
-- circular relationship. Add the second side only after both tables exist.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'offers_application_fk'
          AND conrelid = 'public.offers'::regclass
    ) THEN
        ALTER TABLE public.offers
            ADD CONSTRAINT offers_application_fk
            FOREIGN KEY (application_id)
            REFERENCES public.internship_applications(id)
            ON DELETE SET NULL
            DEFERRABLE INITIALLY DEFERRED;
    END IF;
END;
$$;
CREATE INDEX IF NOT EXISTS idx_offers_application ON public.offers(application_id);

CREATE TABLE IF NOT EXISTS public.announcements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    type varchar(20) NOT NULL DEFAULT 'general' CHECK (type IN ('general','reminder','urgent')),
    recipient_group varchar(40) NOT NULL DEFAULT 'all',
    title varchar(180) NOT NULL,
    body text NOT NULL,
    link_url varchar(255),
    recipient_count bigint NOT NULL DEFAULT 0,
    email_sent_count bigint NOT NULL DEFAULT 0,
    email_failed_count bigint NOT NULL DEFAULT 0,
    telegram_sent_at timestamptz,
    telegram_message_id varchar(80),
    telegram_error varchar(255),
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_announcements_created_by ON public.announcements(created_by);

CREATE TABLE IF NOT EXISTS public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id bigint REFERENCES public.announcements(id) ON DELETE SET NULL,
    recipient_user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    type varchar(20) NOT NULL DEFAULT 'system' CHECK (type IN ('system','general','reminder','urgent')),
    title varchar(180) NOT NULL,
    body text NOT NULL,
    link_url varchar(255),
    recipient_group varchar(40),
    email_to varchar(150),
    email_sent_at timestamptz,
    email_error varchar(255),
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notifications_recipient ON public.notifications(recipient_user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_created_by ON public.notifications(created_by);
CREATE INDEX IF NOT EXISTS idx_notifications_announcement ON public.notifications(announcement_id);

CREATE TABLE IF NOT EXISTS public.activity_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
    action varchar(80) NOT NULL,
    entity_type varchar(80) NOT NULL,
    entity_id bigint,
    metadata jsonb,
    ip_address varchar(45),
    user_agent varchar(255),
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_activity_user_created ON public.activity_logs(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_activity_entity ON public.activity_logs(entity_type, entity_id);

CREATE TABLE IF NOT EXISTS public.placement_change_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(user_id) ON DELETE CASCADE,
    current_offer_id bigint NOT NULL REFERENCES public.offers(id) ON DELETE CASCADE,
    requested_offer_id bigint NOT NULL REFERENCES public.offers(id) ON DELETE CASCADE,
    reason text NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    review_note varchar(500),
    reviewed_at timestamptz,
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pcr_student_status ON public.placement_change_requests(student_id, status);
CREATE INDEX IF NOT EXISTS idx_pcr_status_created ON public.placement_change_requests(status, created_at);
CREATE INDEX IF NOT EXISTS idx_pcr_reviewed_by ON public.placement_change_requests(reviewed_by);

CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token_hash char(64) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    requested_ip varchar(45),
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_password_reset_user ON public.password_reset_tokens(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_password_reset_expiry ON public.password_reset_tokens(expires_at);

CREATE TABLE IF NOT EXISTS public.system_settings (
    setting_key varchar(80) PRIMARY KEY,
    setting_value varchar(255) NOT NULL,
    updated_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    updated_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_system_settings_updated_by ON public.system_settings(updated_by);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    NEW.updated_at = pg_catalog.now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS internship_applications_set_updated_at ON public.internship_applications;
CREATE TRIGGER internship_applications_set_updated_at
BEFORE UPDATE ON public.internship_applications
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS system_settings_set_updated_at ON public.system_settings;
CREATE TRIGGER system_settings_set_updated_at
BEFORE UPDATE ON public.system_settings
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.employers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.offers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.internship_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.placement_change_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.password_reset_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.system_settings ENABLE ROW LEVEL SECURITY;

COMMIT;
