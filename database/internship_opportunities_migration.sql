BEGIN;

CREATE TABLE IF NOT EXISTS public.internship_opportunities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    position_title varchar(150) NOT NULL,
    department varchar(150),
    description text,
    location varchar(150),
    status varchar(20) NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'closed', 'inactive')),
    intake varchar(100),
    application_deadline date,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_internship_opportunities_company
    ON public.internship_opportunities(company_id);
CREATE INDEX IF NOT EXISTS idx_internship_opportunities_status_deadline
    ON public.internship_opportunities(status, application_deadline);

CREATE TABLE IF NOT EXISTS public.opportunity_programmes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id bigint NOT NULL REFERENCES public.internship_opportunities(id) ON DELETE CASCADE,
    programme varchar(180) NOT NULL,
    programme_normalized varchar(180) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_opportunity_programme_normalized
        UNIQUE (opportunity_id, programme_normalized),
    CONSTRAINT chk_opportunity_programme_not_blank
        CHECK (btrim(programme) <> '' AND btrim(programme_normalized) <> '')
);

CREATE INDEX IF NOT EXISTS idx_opportunity_programmes_opportunity
    ON public.opportunity_programmes(opportunity_id);
CREATE INDEX IF NOT EXISTS idx_opportunity_programmes_normalized
    ON public.opportunity_programmes(programme_normalized);

ALTER TABLE public.internship_opportunities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.opportunity_programmes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.internship_opportunities, public.opportunity_programmes FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.internship_opportunities_id_seq, public.opportunity_programmes_id_seq FROM anon, authenticated;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON public.internship_opportunities, public.opportunity_programmes TO internpilih_app;
        GRANT USAGE, SELECT ON SEQUENCE public.internship_opportunities_id_seq, public.opportunity_programmes_id_seq TO internpilih_app;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_staging_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON public.internship_opportunities, public.opportunity_programmes TO internpilih_staging_app;
        GRANT USAGE, SELECT ON SEQUENCE public.internship_opportunities_id_seq, public.opportunity_programmes_id_seq TO internpilih_staging_app;
    END IF;
END;
$$;

COMMIT;
