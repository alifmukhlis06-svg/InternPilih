BEGIN;

ALTER TABLE public.placement_change_requests
    DROP CONSTRAINT IF EXISTS placement_change_requests_status_check;

UPDATE public.placement_change_requests
SET status = 'preparing_request'
WHERE status = 'pending';

ALTER TABLE public.placement_change_requests
    ALTER COLUMN status SET DEFAULT 'preparing_request',
    ADD COLUMN IF NOT EXISTS submitted_at timestamptz,
    ADD COLUMN IF NOT EXISTS revision_requested_at timestamptz,
    ADD COLUMN IF NOT EXISTS revision_deadline timestamptz,
    ADD COLUMN IF NOT EXISTS final_decision_at timestamptz;

ALTER TABLE public.placement_change_requests
    ADD CONSTRAINT placement_change_requests_status_check
    CHECK (status IN (
        'preparing_request', 'documents_complete', 'request_submitted',
        'coordinator_review', 'revision_required', 'approved', 'rejected'
    ));

CREATE UNIQUE INDEX IF NOT EXISTS uq_placement_change_active_student
    ON public.placement_change_requests(student_id)
    WHERE status IN (
        'preparing_request', 'documents_complete', 'request_submitted',
        'coordinator_review', 'revision_required'
    );

CREATE TABLE IF NOT EXISTS public.placement_change_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES public.placement_change_requests(id) ON DELETE CASCADE,
    document_type varchar(40) NOT NULL CHECK (document_type IN (
        'proof_of_sending', 'placement_change_letter', 'company_response'
    )),
    status varchar(20) NOT NULL DEFAULT 'missing' CHECK (status IN (
        'missing', 'uploaded', 'verified', 'rejected'
    )),
    file_name varchar(255),
    storage_bucket varchar(100),
    storage_object_path varchar(500),
    content_type varchar(100),
    byte_size bigint CHECK (byte_size IS NULL OR byte_size >= 0),
    sha256 char(64),
    uploaded_at timestamptz,
    replaced_at timestamptz,
    last_submitted_at timestamptz,
    verified_at timestamptz,
    rejected_at timestamptz,
    reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    rejection_reason varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (request_id, document_type)
);

CREATE INDEX IF NOT EXISTS idx_placement_change_documents_request
    ON public.placement_change_documents(request_id);
CREATE INDEX IF NOT EXISTS idx_placement_change_documents_reviewer
    ON public.placement_change_documents(reviewed_by);
CREATE UNIQUE INDEX IF NOT EXISTS uq_placement_change_document_storage
    ON public.placement_change_documents(storage_bucket, storage_object_path)
    WHERE storage_object_path IS NOT NULL;

DROP TRIGGER IF EXISTS placement_change_documents_set_updated_at ON public.placement_change_documents;
CREATE TRIGGER placement_change_documents_set_updated_at
BEFORE UPDATE ON public.placement_change_documents
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

INSERT INTO public.placement_change_documents (request_id, document_type)
SELECT request.id, required.document_type
FROM public.placement_change_requests request
CROSS JOIN (VALUES
    ('proof_of_sending'),
    ('placement_change_letter'),
    ('company_response')
) AS required(document_type)
ON CONFLICT (request_id, document_type) DO NOTHING;

ALTER TABLE public.placement_change_documents ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON public.placement_change_documents
    FROM PUBLIC, anon, authenticated;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_app') THEN
        GRANT SELECT, INSERT, UPDATE ON public.placement_change_documents TO internpilih_app;
        GRANT USAGE ON SEQUENCE public.placement_change_documents_id_seq TO internpilih_app;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_backend') THEN
        GRANT SELECT, INSERT, UPDATE ON public.placement_change_documents TO internpilih_backend;
        GRANT USAGE ON SEQUENCE public.placement_change_documents_id_seq TO internpilih_backend;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_staging_app') THEN
        GRANT SELECT, INSERT, UPDATE ON public.placement_change_documents TO internpilih_staging_app;
        GRANT USAGE ON SEQUENCE public.placement_change_documents_id_seq TO internpilih_staging_app;
    END IF;
END
$$;

COMMIT;
