BEGIN;

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS google_auth_user_id varchar(100),
    ADD COLUMN IF NOT EXISTS last_login_at timestamptz;

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_google_auth_user_id
    ON public.users(google_auth_user_id)
    WHERE google_auth_user_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_normalized_email
    ON public.users(lower(btrim(email)));

CREATE TABLE IF NOT EXISTS public.authentication_audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
    action varchar(50) NOT NULL CHECK (action IN (
        'google_login_success',
        'password_login_success',
        'login_failure',
        'logout',
        'unauthorized_access_attempt'
    )),
    authentication_method varchar(20) NOT NULL CHECK (
        authentication_method IN ('google','password','session')
    ),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_authentication_audit_user_created
    ON public.authentication_audit_logs(user_id, created_at DESC);

ALTER TABLE public.authentication_audit_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON public.authentication_audit_logs FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON SEQUENCE public.authentication_audit_logs_id_seq FROM PUBLIC, anon, authenticated;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_backend') THEN
        GRANT SELECT, INSERT ON public.authentication_audit_logs TO internpilih_backend;
        GRANT USAGE, SELECT ON SEQUENCE public.authentication_audit_logs_id_seq TO internpilih_backend;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'internpilih_staging_app') THEN
        GRANT SELECT, INSERT ON public.authentication_audit_logs TO internpilih_staging_app;
        GRANT USAGE, SELECT ON SEQUENCE public.authentication_audit_logs_id_seq TO internpilih_staging_app;
    END IF;
END
$$;

COMMIT;
